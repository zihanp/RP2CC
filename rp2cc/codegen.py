"""Deterministic C11 lowering for a checked expression + pool layout."""

import hashlib

from .model import blobs_of

OPERATORS = {"add": "+", "sub": "-", "mul": "*", "and": "&", "or": "|", "xor": "^", "shl": "<<", "lshr": ">>"}


def _literal(n):
    return f"UINT32_C(0x{n:08x})"


def _args(args):
    return ", ".join("uint32_t v_" + a for a in args) or "void"


def _function(k, helpers):
    name = k["name"]
    lines = [f"uint32_t rp_{name}({_args(k['args'])}) {{"]
    seen = {}
    used = set()

    def lower(e):
        if type(e) is int:
            return _literal(e)
        if type(e) is str:
            used.add(e)
            return "v_" + e
        op, a = e[0], tuple(lower(v) for v in e[1:])
        key = (op, *a)
        if key in seen:
            return seen[key]
        if op in OPERATORS:
            expr = f"{a[0]} {OPERATORS[op]} {a[1]}"
        elif op == "not":
            expr = f"~{a[0]}"
        else:
            assert op in ("floor2", "affine_iter")
            helpers.add(op)
            expr = f"rp2cc_{op}_ref({', '.join(a)})"
        out = f"t{len(seen)}"
        seen[key] = out
        lines.append(f"    const uint32_t {out} = {expr};")
        return out

    ret = lower(k["body"])
    for p in k["args"]:
        if p not in used:
            lines.insert(1, f"    (void)v_{p};")
    lines.extend([f"    return {ret};", "}", ""])
    return lines


def render(source, cert):
    h = ["/* Generated by RP2CC. Dynamic word parameters; all arithmetic modulo 2^32. */",
         "#ifndef RP2CC_GENERATED_KERNELS_H", "#define RP2CC_GENERATED_KERNELS_H", "#include <stdint.h>",
         "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    c = ["/* Generated by RP2CC. Inspect alongside certificate.json; C11, 8-bit bytes, 32-bit unsigned int. */",
         '#include "kernels.h"', "#include <limits.h>",
         '_Static_assert(CHAR_BIT == 8 && UINT_MAX == UINT32_MAX, "RP2CC requires 8-bit bytes and 32-bit unsigned int");', ""]
    funcs, helpers = [], set()
    for k in cert["kernels"]:
        h.append(f"uint32_t rp_{k['name']}({_args(k['args'])});")
        funcs.extend(_function(k, helpers))
    if "floor2" in helpers:
        c.extend(["/* Independent scalar reference: copy each lane's sign into the four vacated bits. */",
                  "static inline uint32_t rp2cc_floor_lane_ref(uint32_t bits) {",
                  "    uint32_t lane = bits & UINT32_C(0xffff);",
                  "    return (lane >> 4) | ((UINT32_C(0) - (lane >> 15)) & UINT32_C(0xf000));", "}",
                  "static inline uint32_t rp2cc_floor2_ref(uint32_t word) {",
                  "    return rp2cc_floor_lane_ref(word) | (rp2cc_floor_lane_ref(word >> 16) << 16);", "}", ""])
    if "affine_iter" in helpers:
        c.extend(["/* All trip counts and coefficients are visible to the downstream optimizer. */",
                  "static inline uint32_t rp2cc_affine_iter_ref(uint32_t x, uint32_t n, uint32_t a, uint32_t b) {",
                  "    for (uint32_t i = 0; i < n; ++i) x = x * a + b;", "    return x;", "}", ""])
    c.extend(funcs)
    blobs = blobs_of(source)
    pool = bytes.fromhex(cert["pool"]["bytes"])
    if pool:
        align = max(a for _, _, a in blobs)
        c.append(f"_Alignas({align}) static const uint8_t rp2cc_pool[{len(pool)}] = {{")
        for i in range(0, len(pool), 16):
            c.append("    " + ", ".join(f"0x{v:02x}" for v in pool[i:i+16]) + ",")
        c.extend(["};", ""])
    for name, data, _ in blobs:
        h.append(f"uint32_t rp_rom_{name}(uint32_t index); /* {len(data)} bytes; outside the object: 0 */")
        c.append(f"uint32_t rp_rom_{name}(uint32_t index) {{")
        if data:
            off = cert["pool"]["offsets"][name]
            c.append(f"    return index < UINT32_C({len(data)}) ? rp2cc_pool[UINT32_C({off}) + index] : UINT32_C(0);")
        else:
            c.extend(["    (void)index;", "    return UINT32_C(0);"])
        c.extend(["}", ""])
    h.extend(["", "#ifdef __cplusplus", "}", "#endif", "#endif", ""])
    return {"kernels.c": "\n".join(c).encode("ascii"), "kernels.h": "\n".join(h).encode("ascii")}


def hashes(outputs):
    return {name: hashlib.sha256(data).hexdigest() for name, data in outputs.items()}
